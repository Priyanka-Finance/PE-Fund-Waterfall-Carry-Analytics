"""Headline results as Markdown, for the README.

The README quotes model results.  To stop those figures drifting away from the
code, the block between the two markers is generated by this module
(``python scripts/update_readme.py``) and a test fails if it is out of date.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd

START, END = "<!-- results:start -->", "<!-- results:end -->"


def _pct(value: float) -> str:
    return "n/a" if pd.isna(value) else f"{value:.1%}"


def _mult(value: float) -> str:
    return "n/a" if pd.isna(value) else f"{value:.2f}x"


def _money(value: float) -> str:
    return f"{value + 0.0:,.1f}"


def _month(value: Any) -> str:
    return "none" if value is None or pd.isna(value) else f"{pd.Timestamp(value):%b %Y}"


def _table(header: list[str], rows: list[list[str]], text_columns: int = 1) -> list[str]:
    align = ["---"] * text_columns + ["---:"] * (len(header) - text_columns)
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(align) + " |"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def results_markdown(bundle: dict[str, Any]) -> str:
    """The generated README block for a pipeline bundle (scenarios included if present)."""
    result = bundle["result"]
    cfg, s = result.config, bundle["summary"]
    bridge = bundle["bridge"].set_index("step")["irr_impact_bps"]
    unit = f"{cfg.fund.currency} {cfg.fund.unit}"
    lines = [
        START,
        f"**{cfg.fund.name}** - {_money(cfg.fund.committed_capital)} of commitments, "
        f"{len(cfg.deals)} deals, money in {unit}.",
        "",
    ]
    costs = [("fees", "Management fees"), ("expenses", "Partnership expenses"), ("carry", "Carried interest")]
    if abs(bridge["Financing and timing"]) >= 0.5:
        costs.append(("financing and timing", "Financing and timing"))
    costs_label = "of which " + " / ".join(name for name, _ in costs)
    costs_value = " / ".join(f"{-bridge[step]:,.0f}" for _, step in costs) + " bps"
    lines += _table(
        ["Base case, at liquidation", "Result"],
        [
            ["Gross IRR / gross MOIC (deal level)", f"{_pct(s['gross_irr'])} / {_mult(s['gross_moic'])}"],
            ["Net IRR / net TVPI (to LPs)", f"{_pct(s['net_irr'])} / {_mult(s['tvpi'])}"],
            ["Gross-to-net spread", f"{-bridge['Net return to LPs']:,.0f} bps"],
            [costs_label, costs_value],
            ["LP capital paid in / distributed", f"{_money(s['paid_in'])} / {_money(s['distributed'])}"],
            ["Management fees, net of offsets", _money(s["total_management_fees"])],
            ["Carried interest, net of clawback", _money(s["carry_net"])],
            ["GP and manager share of gross profit", _pct(s["gp_share_of_gross_profit"])],
        ],
    )
    table = bundle["comparison"]["table"]
    lines += ["", "**Same deals, two waterfalls**", ""]
    lines += _table(
        ["Waterfall", "Net IRR", "Net TVPI", "Carry paid", "Clawback", "First carry", "Average carry timing"],
        [
            [
                row.waterfall,
                _pct(row.net_irr),
                _mult(row.tvpi),
                _money(row.carry_gross),
                _money(row.clawback_paid),
                _month(row.first_carry_date),
                f"year {row.average_carry_timing_years:.1f}",
            ]
            for row in table.itertuples()
        ],
    )
    scenarios = bundle.get("scenario_table")
    if scenarios is not None:
        lines += ["", "**Scenarios**", ""]
        lines += _table(
            ["Scenario", "Waterfall", "Gross MOIC", "Net IRR", "Net TVPI", "Carry paid", "Clawback", "Carry kept"],
            [
                [
                    row.label,
                    "deal-by-deal" if row.waterfall == "american" else "whole-of-fund",
                    _mult(row.gross_moic),
                    _pct(row.net_irr),
                    _mult(row.tvpi),
                    _money(row.carry_gross),
                    _money(row.clawback_paid),
                    _money(row.carry_net),
                ]
                for row in scenarios.itertuples()
            ],
            text_columns=2,
        )
    lines += ["", "*Figures are rounded separately, so components may not add exactly to totals.*", END]
    return "\n".join(lines)


def current_block(readme: str | Path) -> str:
    """The block currently in the README, markers included."""
    text = Path(readme).read_text(encoding="utf-8")
    start, end = text.index(START), text.index(END) + len(END)
    return text[start:end]


def update_readme(readme: str | Path, bundle: dict[str, Any]) -> bool:
    """Rewrite the README block from ``bundle``.  Returns whether the file changed."""
    path = Path(readme)
    text = path.read_text(encoding="utf-8")
    start, end = text.index(START), text.index(END) + len(END)
    updated = text[:start] + results_markdown(bundle) + text[end:]
    if updated == text:
        return False
    path.write_text(updated, encoding="utf-8")
    return True
